#!/usr/bin/env bash
# Regenerates requirements.lock (the full transitive pin set) from constraints.txt in a clean Ubuntu 24.04 container.
# Only needed when deliberately changing the stack; the committed lock is what everyone installs.
#   ./resolve.sh
set -euo pipefail
cd "$(dirname "$0")"
docker run --rm --platform linux/amd64 -v "$PWD:/stack" -w /stack \
  ubuntu:24.04@sha256:9a04f13b3f80ef056361e30868593b1cfd2279fe19e4081cb93a90bf56819d6a bash -euo pipefail -c '
  export DEBIAN_FRONTEND=noninteractive
  apt-get update -qq && apt-get install -y -qq --no-install-recommends python3.12 python3.12-venv git ca-certificates >/dev/null
  . ./versions.env
  python3.12 -m venv /v && . /v/bin/activate && pip install -q -U pip==25.2
  # CPU torch wheels: Neuron never uses CUDA, and the default PyPI torch drags in ~3 GB of nvidia-* packages.
  # vLLM serving is not in this image: use the AWS 2.28 vLLM container pinned by digest (see README).
  pip install -q --extra-index-url https://pip.repos.neuron.amazonaws.com \
      --extra-index-url https://download.pytorch.org/whl/cpu -c constraints.txt \
      neuronx-cc torch-neuronx libneuronxla neuronx-distributed neuronx-distributed-inference nki \
      "torch==2.9.0+cpu" torch-xla "torchvision==0.24.0+cpu" transformers
  { echo "# Generated by resolve.sh on $(date -u +%F) from constraints.txt. Install with --no-deps."
    echo "--extra-index-url https://pip.repos.neuron.amazonaws.com"
    echo "--extra-index-url https://download.pytorch.org/whl/cpu"
    pip freeze --exclude-editable | sort -f; } > requirements.lock
  echo "locked $(grep -vc "^[#-]" requirements.lock) packages"'
